const TWENTY_FOUR_HOURS_MS = 24 * 60 * 60 * 1000

/**
 * Calculates the error rate percentage for the last 24 hours directly from
 * the logs generated by the backend performance logging middleware.
 */
export function calculateLast24hErrorRateFromMiddlewareLogs(
  telemetry: ApiPerformanceTelemetry,
  nowMs: number = Date.now(),
): Last24HoursErrorRateData {
  return computePast24HoursPerformanceSummary(telemetry, nowMs)
}

